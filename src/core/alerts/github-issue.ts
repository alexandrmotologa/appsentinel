import type { IncidentCluster } from '../../types/incident.js';

export interface GitHubIssueConfig {
  enabled: boolean;
  repo: string; // e.g. "myorg/my-mobile-app"
  token?: string;
  labels?: string[];
}

export class GitHubIssueCreator {
  private config: GitHubIssueConfig;

  constructor(config: GitHubIssueConfig) {
    this.config = config;
  }

  public async createIssue(incident: IncidentCluster): Promise<{
    success: boolean;
    issueUrl?: string;
    issueNumber?: number;
    error?: string;
  }> {
    const token = this.config.token || process.env.GITHUB_TOKEN;
    if (!token) {
      return {
        success: false,
        error: 'GITHUB_TOKEN is required to create GitHub issues.',
      };
    }

    const title = `[${incident.severity}] ${incident.appName} v${incident.appVersion}: ${incident.category} Spike (${incident.subsystem || 'Crash'})`;
    const body = this.formatIssueBody(incident);
    const labels = this.config.labels || ['incident', 'bug', 'appsentinel', incident.severity.toLowerCase()];

    const url = `https://api.github.com/repos/${this.config.repo}/issues`;

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`,
          'User-Agent': 'AppSentinel-IssueCreator/1.0',
          'Accept': 'application/vnd.github+json',
        },
        body: JSON.stringify({
          title,
          body,
          labels,
        }),
      });

      if (!response.ok) {
        const text = await response.text();
        throw new Error(`GitHub API error HTTP ${response.status}: ${text}`);
      }

      const data = (await response.json()) as { html_url: string; number: number };
      return {
        success: true,
        issueUrl: data.html_url,
        issueNumber: data.number,
      };
    } catch (err) {
      return {
        success: false,
        error: err instanceof Error ? err.message : String(err),
      };
    }
  }

  public formatIssueBody(incident: IncidentCluster): string {
    const devices =
      incident.deviceModels.length > 0 ? incident.deviceModels.join(', ') : 'Not specified';
    const osVersions =
      incident.osVersions.length > 0 ? incident.osVersions.join(', ') : 'Not specified';

    let md = `## Incident Overview\n\n`;
    md += `* **Application:** ${incident.appName} (${incident.platform.toUpperCase()})\n`;
    md += `* **Release Version:** \`${incident.appVersion}\`\n`;
    md += `* **Incident Category:** \`${incident.category}\`\n`;
    md += `* **Suspected Subsystem:** \`${incident.subsystem || 'UNKNOWN'}\`\n`;
    md += `* **Severity:** \`${incident.severity}\`\n`;
    md += `* **Reports in Rolling Window:** **${incident.reviewCount}** reports\n`;
    md += `* **First Seen:** ${incident.firstSeenAt}\n`;
    md += `* **Last Seen:** ${incident.lastSeenAt}\n\n`;

    md += `### Root Cause Summary\n`;
    md += `> ${incident.rootCauseSummary}\n\n`;

    if (incident.suggestedMitigation) {
      md += `### Suggested Action & Mitigation\n`;
      md += `🛠️ **${incident.suggestedMitigation}**\n\n`;
    }

    md += `### Affected Environment\n`;
    md += `* **Devices:** ${devices}\n`;
    md += `* **Operating Systems:** ${osVersions}\n\n`;

    if (incident.sampleReviews && incident.sampleReviews.length > 0) {
      md += `### Customer Feedback Excerpts\n\n`;
      for (const r of incident.sampleReviews.slice(0, 3)) {
        md += `> "${r.content.replace(/\s+/g, ' ')}" — *${r.author} (⭐${r.rating})*\n\n`;
      }
    }

    md += `---\n*Automated incident report generated by AppSentinel.*`;
    return md;
  }
}
